repo="$HOME/gpunode"
url='https://github.com/joxydev/gpunode.git'
source_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
[[ -f "$source_dir/31_language_vps.sh" ]] || { echo 'Положите оба скрипта в одну директорию.' >&2; exit 1; }
