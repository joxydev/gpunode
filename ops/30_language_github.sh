cd "$repo"
[[ $(git remote get-url origin) == "$url" ]] || { echo 'Ожидался origin joxydev/gpunode.' >&2; exit 1; }
[[ -z $(git status --porcelain) ]] || { echo 'Есть локальные изменения. Сохраните их до запуска скрипта.' >&2; exit 1; }
git fetch origin main
git switch main
remote_sha=$(git rev-parse origin/main)
if git cat-file -e origin/main:backend/prisma/migrations/202609230001_user_language/migration.sql 2>/dev/null; then
  git merge --ff-only origin/main
  printf '\nЯзыковая версия уже опубликована. Синхронизирован коммит %s.\n' "$(git rev-parse HEAD)"
  exit 0
fi
[[ $remote_sha == "$base" ]] || { echo 'Базовый коммит GitHub изменился: патч нельзя применять автоматически.' >&2; exit 1; }
if [[ $(git rev-parse HEAD) != "$base" ]]; then
  if git cat-file -e HEAD:backend/prisma/migrations/202609230001_user_language/migration.sql 2>/dev/null && git merge-base --is-ancestor origin/main HEAD; then
    if command -v gh >/dev/null && gh auth status >/dev/null 2>&1; then gh auth setup-git >/dev/null; fi
    git push origin main
    printf '\nОпубликован ранее собранный коммит %s.\n' "$(git rev-parse HEAD)"
    exit 0
  fi
  echo 'Локальная main отличается от базы. Нужна ручная проверка.' >&2; exit 1
fi

